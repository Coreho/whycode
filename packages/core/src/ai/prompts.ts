// Builds the requests for the AI comment pass and for refactor mode. Each
// system prompt depends only on the comment level, so it stays byte-identical
// across files and can be cached by the provider; everything file-specific
// goes in the user message.
import type { CommentLevel } from "../config.js";
import { commentPlanJsonSchema } from "./comment-plan.js";
import type { AIRequest } from "./provider.js";
import { refactorPlanJsonSchema } from "./refactor-plan.js";

export interface CommentPromptInput {
  /** File path shown to the model for context, ideally repo-relative. */
  path: string;
  code: string;
  languageId: string;
  commentLevel: CommentLevel;
}

const ROLE = `You write explanatory comments for source code that was generated by an AI assistant, so that the people who maintain it can understand it. You never change the code. You return a plan of comments to insert, and WhyCode inserts them as line comments.`;

const GOOD_COMMENTS = `What makes a good comment:
- It explains why: the intent, a constraint, a trade-off, an edge case, or a consequence that isn't obvious. Readers can already see what each line does.
- It is specific to this code. "Retries only 429 and 5xx responses" is useful when the condition proves it; "Retry logic" is not. Do not invent a deployment incident or other external reason.
- It is short. One sentence is usually enough; use two or three lines only when the reasoning needs them.
- It is plain and factual, written the way a careful engineer explains code to a colleague. Skip filler such as "This function..." or "Here we...".
- It doesn't restate names or types ("Increment the counter", "Returns a string").
- It doesn't invent reasons. State observable behavior or a consequence supported by the code. Intent, business policy, historical reasons and external guarantees require explicit supporting context; an existing comment is a claim to check, not proof. When the rationale is uncertain, omit the comment rather than guessing or hedging.
- Documented behavior of the language, its standard library, or a framework or platform API the code calls is a fact, not a guess. When the code depends on such behavior in a way a reader could miss, state the behavior itself; don't extend it into a promise about this project's own dependencies or data.
- Before making a claim, look for a counterexample in the branches, boundary values, exceptions, rounding, and aliasing. Words such as "always", "never", "safe", "only" and "otherwise" require support across all relevant paths. A positive-integer guard rejects fractions too: do not claim every rejected value would skip a loop.
- Do not claim rounding prevents every floating-point error, a shallow copy prevents nested mutation, a retry catches exceptions it does not catch, or a local check guarantees behavior of an external dependency.
- Distinguish an algorithm's usual purpose from its guarantees. If a claim needs input preconditions that this code does not enforce, state those conditions explicitly or omit the claim. Prefer a precise local observation over a broad promise that totals are exact, delivery succeeds, or an error reaches the caller; finally blocks and unchecked inputs can invalidate those promises.
- It earns its place. When a reader would learn nothing new from a comment, leave it out: fewer, better comments keep the code easy to read.`;

const PLACEMENT = `Where comments go:
- Each insertion is placed above the line number you give, at that line's indentation. Line numbers refer to the numbered code in the request.
- Target the first line of the code the comment describes (for a group of statements, the first statement), never a line before it.
- Never target a line inside a multi-line string, template literal, docstring, or JSX/HTML text. A comment there would become part of the text, so WhyCode drops it.
- Never target the line right after a line that ends with a backslash line continuation.
- Leave existing comments and docstrings alone. If something already has a summary comment or docstring, don't add another.
- Write comment text without comment markers (no #, //, or /*). WhyCode adds them.`;

const EXISTING_COMMENTS = `Existing comments:
List an existing comment in existingCommentSuggestions only when it is wrong, misleading, or out of date with the code. Give its line number, its original text, your replacement, and the reason. Don't suggest rewrites that are only about style.`;

const LEVEL_GUIDANCE: Readonly<Record<CommentLevel, string>> = {
  light: `Comment level: light.
Keep the code uncluttered: comment only what a careful maintainer wouldn't see at a glance, and many functions need none. An empty insertions list is fine when nothing qualifies, but don't leave out a comment that would stop someone from breaking the code while tidying it. Add a one-line summary above a function, method, or class only when its name and signature don't already make its purpose clear, saying what it is for rather than how it works; skip it for self-explanatory code such as small helpers, simple getters, event handlers, and straightforward components. Skip obvious validation, error messages, and loops whose names and conditions already explain them.
Inside function bodies, comment the non-obvious things the code demonstrates, such as:
- ordering or timing that matters, such as something set up before the event it waits for, or work awaited before a resource is closed;
- reliance on documented behavior of a library, framework or platform, stated as that behavior;
- values a control, type or caller doesn't enforce, and error handling that fails open or fails closed;
- rounding boundaries, aliasing, and limits that are easy to change by mistake.
Test files count too: comment setup or ordering that tests depend on, and why a test bypasses a normal check.
Never fill a comment quota. If an existing comment already explains something, don't add a second explanation of the same fact. Most lines get no comment.`,
  medium: `Comment level: medium.
Add a one-line summary above each function, method, and class that lacks one, saying what it is for rather than how it works, and comment non-obvious reasons as at the light level. Also put a short note above each logical block inside a function (for example setup, validation, the main loop, cleanup), so a reader can skim its structure. Still skip lines whose purpose is obvious.`,
  heavy: `Comment level: heavy.
The reader is learning this language or this codebase. Explain nearly every statement or small group of statements: what it does and why it is needed, including language features and library calls a beginner might not know. Keep each comment short and accurate; the goal is understanding, not padding.`,
};

const EXAMPLE = `Example. For this code, at the light level:
1| def fetch_rates(client):
2|     for attempt in range(3):
3|         try:
4|             return client.get("/rates", timeout=5)
5|         except TimeoutError:
6|             time.sleep(2 ** attempt)
7|     return CACHED_RATES

a good reply is:
{"insertions":[{"line":6,"position":"above","text":"Waits after every timeout, including the last attempt before returning cached rates."}],"existingCommentSuggestions":[]}

For a helper that only checks a positive integer and returns it, the light-level reply is:
{"insertions":[],"existingCommentSuggestions":[]}
The validation is already explicit; a speculative explanation would add risk, not understanding.`;

const REPLY_FORMAT = `Reply with JSON only, in this shape:
{"insertions":[{"line":<number>,"position":"above","text":"<comment text>"}],"existingCommentSuggestions":[{"line":<number>,"original":"<text>","suggested":"<text>","reason":"<text>"}]}`;

/** The full system prompt for one comment level. Exported for tests. */
export function systemPrompt(commentLevel: CommentLevel): string {
  return [
    ROLE,
    GOOD_COMMENTS,
    PLACEMENT,
    EXISTING_COMMENTS,
    LEVEL_GUIDANCE[commentLevel],
    EXAMPLE,
    REPLY_FORMAT,
  ].join("\n\n");
}

export function buildCommentPrompt(input: CommentPromptInput): AIRequest {
  const user = [
    `File: ${input.path.replace(/\\/g, "/")} (${input.languageId})`,
    "",
    numberLines(input.code),
  ].join("\n");
  return {
    system: systemPrompt(input.commentLevel),
    user,
    jsonSchema: commentPlanJsonSchema,
  };
}

const REFACTOR_ROLE = `You refactor source code that was generated by an AI assistant, so that the people who maintain it can understand and change it. You return the complete rewritten file. The user reviews a diff before anything is saved, and the project's tests may be run against your version.`;

const REFACTOR_RULES = `How to refactor:
- Make the code easier to read: clear names for local variables and private helpers, short functions, early returns instead of deep nesting, no duplicated logic, no dead code.
- Keep what the code does. Change behavior only to fix a clear bug, and list every such fix in changes.
- Keep the public interface: exported names, function signatures, class and method names, and file-level side effects that other code may rely on.
- Keep the same language, imports you still use, and dependencies. Don't add new libraries.
- Keep existing comments that are still true; update ones your changes make wrong.
- Return the whole file, never a fragment or a diff, without Markdown fences inside the code.`;

const REFACTOR_REPLY_FORMAT = `Reply with JSON only, in this shape:
{"code":"<the entire rewritten file>","changes":["<one short line per change, e.g. Split parse_order into validation and pricing helpers>"]}`;

/** The full refactor-mode system prompt for one comment level. Exported for tests. */
export function refactorSystemPrompt(commentLevel: CommentLevel): string {
  return [
    REFACTOR_ROLE,
    REFACTOR_RULES,
    `Also add comments to the rewritten code, following these rules.\n${GOOD_COMMENTS}`,
    LEVEL_GUIDANCE[commentLevel],
    REFACTOR_REPLY_FORMAT,
  ].join("\n\n");
}

export function buildRefactorPrompt(input: CommentPromptInput): AIRequest {
  const user = [
    `File: ${input.path.replace(/\\/g, "/")} (${input.languageId})`,
    "",
    input.code,
  ].join("\n");
  return {
    system: refactorSystemPrompt(input.commentLevel),
    user,
    jsonSchema: refactorPlanJsonSchema,
  };
}

/** Prefixes each line with its 1-based number, e.g. "12| return x". */
export function numberLines(code: string): string {
  return code
    .split("\n")
    .map((line, index) => `${index + 1}| ${line}`)
    .join("\n");
}
